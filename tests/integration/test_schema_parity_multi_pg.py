FAKE_WS_PG = textwrap.dedent(
    """
    import json, os, re, sys
    import psycopg
    admin = os.environ["FAKE_WSPG_ADMIN"]
    log = os.environ["FAKE_WSPG_LOG"]
    def url(db):
        return re.sub(r"/[^/?]*(\\?|$)", "/" + db + r"\\1", admin, count=1)
    cmd = sys.argv[1]
    if cmd == "start":
        print("DATABASE_URL=" + admin)
    elif cmd == "createdb":
        with psycopg.connect(admin, autocommit=True) as c:
            c.execute(('CREATE DATABASE "%s"' % sys.argv[2]).encode())
        open(log, "a").write(sys.argv[2] + "\\n")
        print("created\\n" + url(sys.argv[2]))
    elif cmd == "psql":
        args = sys.argv[3:]
        assert all(f == "-c" for f in args[::2]) and not any("\\\\" in a for a in args[1::2])
        with psycopg.connect(url(sys.argv[2])) as c:
            c.read_only = True
            print(c.execute(args[-3].encode()).fetchone()[0])
    else:
        sys.exit(2)
    """
)


class _LocalWorkspace:
    """A workspace that IS this machine: /workspace -> the fixture dir, python3 -> this one."""

    def __init__(self, root: Path, env: dict[str, str]) -> None:
        self.root = root
        self.env = env
        self.job: dict[str, Any] = {}

    def _run(self, argv: list[str], timeout: int) -> dict[str, Any]:
        argv = [sys.executable if a == "python3" else a for a in argv]
        proc = subprocess.run(  # noqa: S603 - test-local stand-in for the workspace exec
            argv, capture_output=True, text=True, timeout=timeout, env=self.env, check=False
        )
        return {"exit_code": proc.returncode, "stdout": proc.stdout, "stderr": proc.stderr}

    async def exec(self, container, tenant_id, argv, workdir, timeout):
        return self._run(argv, timeout)

    async def exec_async(self, container, tenant_id, argv, workdir, timeout):
        run_dir = Path(argv[-1])
        cfg = json.loads((run_dir / "driver_config.json").read_text())
        for side in cfg["sides"]:  # the checkout lives under the fixture, not /workspace
            side["workdir"] = side["workdir"].replace("/workspace", str(self.root), 1)
        cfg["workspace_root"] = str(self.root)
        (run_dir / "driver_config.json").write_text(json.dumps(cfg))
        self.job = {"status": "completed", **self._run(argv, timeout)}
        return {"job_id": "local-1", "status": "queued"}

    async def get_exec_job(self, container, tenant_id, job_id):
        return self.job


