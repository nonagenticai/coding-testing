async def test_async_driver_runs_every_step_for_real(local_ws):
    req = SchemaDiffWorkspaceRunRequest.model_validate(
        {
            "sources": [
                {"name": "notes", "workdir": "source",
                 "migrate_command": [sys.executable, "-m", "alembic", "-c", "alembic.ini",
                                     "upgrade", "head"]},
            ],
            "target": {"workdir": "target",
                       "migrate_command": [sys.executable, "../apply_sql_migrations.py",
                                           "migrations"]},
        }
    )  # fmt: skip
    runs = SchemaParityRuns(local_ws)
    started = await runs.start("ws-1", None, req)
    assert started.status == "queued"
    done = await runs.poll("ws-1", None, started.run_id)
    res = done.result
    assert res is not None and done.status == "completed", res
    assert res.computed is True and res.equal is True, res.model_dump()
    assert [s["stage"] for s in res.steps] == [
        "ws_pg_start",
        "createdb_source:notes",
        "createdb_target",
        "migrate_source:notes",
        "migrate_target",
        "introspect_source:notes",
        "introspect_target",
    ]
    assert all(":***@" in s["command"][1] for s in res.steps if s["stage"].startswith("migrate"))

    # Negative control: a failing target migration -> failed, not computed, stage named.
    req.target.migrate_command = [sys.executable, "-c", "import sys; sys.exit(4)"]
    started = await runs.start("ws-1", None, req)
    done = await runs.poll("ws-1", None, started.run_id)
    assert done.status == "failed" and done.result is not None
    assert done.result.computed is False and done.result.stage == "migrate_target"
    assert "exit 4" in (done.result.error or "")
